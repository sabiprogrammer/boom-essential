import type { AppointmentStatus, EnquiryStatus } from "@/lib/admin/shared/types";

/**
 * Shapes of the REAL enquiry data shown in /admin (read from Supabase), as opposed to the dashboard preview's
 * fictional records. The database has five divisions, one more than the preview ("general"), so the preview's
 * DivisionId is not reused. Statuses are the same four and four values, so those types are shared.
 */
export type { AppointmentStatus, EnquiryStatus };

export type AdminDivision = "general" | "energy" | "security" | "foods" | "industrial-equipment";

export type StatusFilter = EnquiryStatus | "all";
export type DivisionFilter = AdminDivision | "all";

export type EnquiryRecord = {
  id: string;
  /** BOOM-YYYY-NNNNN, generated by the database. */
  reference: string;
  fullName: string;
  /** Exactly as the customer typed it. */
  phone: string;
  /** Normalised +234... form set by the server, or null. */
  phoneE164: string | null;
  email: string | null;
  organisation: string | null;
  location: string | null;
  division: AdminDivision;
  /** Services (energy, security); empty when none. */
  requestedService: string[];
  /** Products (foods, industrial equipment); empty when none. */
  requestedItem: string[];
  message: string;
  status: EnquiryStatus;
  source: string;
  /** ISO 8601 instants. */
  createdAt: string;
  updatedAt: string;
};

export type AppointmentRecord = {
  id: string;
  enquiryId: string;
  /** The appointment this one replaced (a reschedule creates a new record and keeps the old one), or null. */
  rescheduledFromId: string | null;
  status: AppointmentStatus;
  /** YYYY-MM-DD */
  preferredDate: string;
  /** HH:MM, 24-hour, in `timezone` */
  preferredTime: string;
  timezone: string;
  confirmedDate: string | null;
  confirmedTime: string | null;
  venue: string | null;
  schedulingNote: string | null;
  /** When an administrator confirmed it (an ISO instant), or null. */
  confirmedAt: string | null;
  createdAt: string;
};

export type NoteRecord = {
  id: string;
  content: string;
  createdAt: string;
  /** True when the signed-in administrator wrote it. Authors are otherwise not named (see CLAUDE.md). */
  mine: boolean;
};

export type ActivityAction =
  | "enquiry_received"
  | "enquiry_status_changed"
  | "appointment_requested"
  | "appointment_status_changed"
  | "appointment_confirmed"
  | "appointment_cancelled"
  | "note_added";

export type ActivityRecord = {
  id: string;
  action: ActivityAction;
  actorType: "admin" | "system";
  createdAt: string;
  fromStatus: string | null;
  toStatus: string | null;
};

/** What the list is showing: parsed from the URL, never trusted. */
export type EnquiryListQuery = {
  search: string;
  status: StatusFilter;
  division: DivisionFilter;
  page: number;
};

export type EnquiryListResult = {
  rows: EnquiryRecord[];
  /** Matches for the current search, division AND status. */
  total: number;
  /** Per status for the current search and division, so each filter chip shows what it would return. */
  counts: Record<StatusFilter, number>;
  /** The page actually shown (clamped into range). */
  page: number;
  pageCount: number;
  pageSize: number;
};

export type EnquiryDetailData = {
  enquiry: EnquiryRecord;
  appointments: AppointmentRecord[];
  notes: NoteRecord[];
  activity: ActivityRecord[];
};
