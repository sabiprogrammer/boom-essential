import type { EnquirySubmission, FieldErrors } from "./types";

/**
 * The wire contract of POST /api/enquiries, shared by the browser (lib/enquiry/submit.ts) and the server
 * (lib/enquiry/server/). Types and constants only: no logic, no imports of server code.
 *
 * The request carries what the visitor typed plus a random `submissionId` the browser makes for each form attempt
 * and re-sends on a retry, so a double click or a lost response can never create two enquiries. It deliberately has
 * NO field for an id, a reference, a status, a source or a timestamp: the server and the database own those, and
 * anything extra in a request is ignored.
 */

export const enquiryEndpoint = "/api/enquiries";

/** Requests larger than this are refused before they are parsed (the longest valid request is about 3 KB). */
export const enquiryRequestMaxBytes = 16 * 1024;

export type EnquiryApiRequest = EnquirySubmission & { submissionId: string };

export type EnquiryApiSuccess = {
  ok: true;
  /** The BOOM-YYYY-NNNNN reference generated by the database. */
  reference: string;
  appointmentRequested: boolean;
};

export type EnquiryApiFailureCode =
  | "invalid" //        a field failed validation (see fieldErrors), or the body was not understood
  | "rejected" //       refused as spam, a cross-site request or data the database would not accept
  | "rate_limited" //   too many enquiries from this client recently
  | "too_large" //      body over the size limit
  | "unsupported" //    not JSON
  | "unavailable"; //   the service could not save the enquiry (nothing was saved)

export type EnquiryApiFailure = {
  ok: false;
  code: EnquiryApiFailureCode;
  /** Safe to show to the visitor. Never contains internal details. */
  message: string;
  fieldErrors?: FieldErrors;
};

export type EnquiryApiResponse = EnquiryApiSuccess | EnquiryApiFailure;

const REFERENCE = /^BOOM-\d{4}-\d{5,}$/;

export function isEnquiryReference(value: unknown): value is string {
  return typeof value === "string" && REFERENCE.test(value);
}
